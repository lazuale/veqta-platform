"""Проверяем права, обновление и восстановление в одноразовых кластерах."""
import os
import subprocess
import sys

import psycopg
from psycopg import sql


def connect(contour, *, migration=False, database_contour=None, port=None):
    kind = "migrator" if migration else "runtime"
    role = f"svc_platform_{contour}" + ("_migrator" if migration else "")
    credential = "RESTORED" if port else contour.upper()
    return psycopg.connect(
        host="127.0.0.1", port=port or os.environ["DB_PORT"], sslmode="disable",
        dbname=f"veqta_{database_contour or contour}", user=role,
        password=os.environ[f"VEQTA_TEST_{credential}_{kind.upper()}"], connect_timeout=5,
        autocommit=True,
    )


def check_isolation():
    for contour, other in (("dev", "prod"), ("prod", "dev")):
        for migration in (False, True):
            try:
                connect(contour, migration=migration, database_contour=other).close()
            except psycopg.OperationalError as error:
                assert "permission denied for database" in str(error), error
            else:
                raise AssertionError(f"Разрешено подключение {contour} к {other}")

        # Пробные объекты получают права штатной следующей миграции.
        with connect(contour, migration=True) as owner, connect(contour) as runtime:
            owner.execute("""
                CREATE TABLE public.veqta_acl_probe (id bigint GENERATED BY DEFAULT AS IDENTITY, n integer);
                CREATE FUNCTION public.veqta_acl_probe() RETURNS integer LANGUAGE sql AS 'SELECT 1'
            """)
            try:
                assert runtime.execute("INSERT INTO public.veqta_acl_probe (n) VALUES (7) RETURNING id").fetchone() == (1,)
                assert runtime.execute("SELECT n FROM public.veqta_acl_probe").fetchone() == (7,)
                assert runtime.execute("UPDATE public.veqta_acl_probe SET n=8").rowcount == 1
                assert runtime.execute("DELETE FROM public.veqta_acl_probe").rowcount == 1
                for statement in (
                    "SELECT last_value FROM public.veqta_acl_probe_id_seq",
                    "SELECT setval('public.veqta_acl_probe_id_seq', 8)",
                    "SELECT public.veqta_acl_probe()",
                ):
                    try:
                        runtime.execute(statement)
                    except psycopg.errors.InsufficientPrivilege:
                        continue
                    raise AssertionError(f"Превышены права по умолчанию: {statement}")
            finally:
                owner.execute("DROP TABLE public.veqta_acl_probe; DROP FUNCTION public.veqta_acl_probe()")
    print("DEV/PROD: изоляция CONNECT обеих ролей и фактические права новых объектов подтверждены")


def inventory(conn):
    queries = {
        "база": """SELECT datdba::regrole::text, datacl::text
                   FROM pg_database WHERE datname=current_database()""",
        "схема": "SELECT nspowner::regrole::text, nspacl::text FROM pg_namespace WHERE nspname='public'",
        "таблицы, последовательности, индексы": """
            SELECT relname, relkind, relowner::regrole::text,
                   CASE WHEN relkind<>'i' THEN ARRAY(
                       SELECT item::text FROM unnest(coalesce(relacl, acldefault(
                           (CASE WHEN relkind='S' THEN 's' ELSE 'r' END)::"char", relowner
                       ))) AS item ORDER BY 1
                   ) END,
                   CASE WHEN relkind='i' THEN pg_get_indexdef(oid) END
            FROM pg_class WHERE relnamespace='public'::regnamespace AND relkind IN ('r','S','i')
            ORDER BY relname
        """,
        "функции": """
            SELECT proname, proowner::regrole::text, proacl::text, pg_get_functiondef(oid)
            FROM pg_proc WHERE pronamespace='public'::regnamespace ORDER BY proname
        """,
        "триггеры": """
            SELECT tgrelid::regclass::text, tgname, tgenabled, pg_get_triggerdef(oid)
            FROM pg_trigger WHERE NOT tgisinternal AND tgrelid IN
                (SELECT oid FROM pg_class WHERE relnamespace='public'::regnamespace)
            ORDER BY 1, 2
        """,
        "ограничения": """
            SELECT conrelid::regclass::text, conname, contype, convalidated, condeferrable, condeferred,
                   -- При восстановлении PG19 может перенести это приведение на элементы массива.
                   replace(pg_get_constraintdef(oid),
                       '(ARRAY[''draft''::character varying, ''closed''::character varying])::text[]',
                       'ARRAY[(''draft''::character varying)::text, (''closed''::character varying)::text]')
            FROM pg_constraint WHERE connamespace='public'::regnamespace ORDER BY 1, 2
        """,
        "права по умолчанию": """
            SELECT defaclrole::regrole::text, defaclnamespace::regnamespace::text,
                   defaclobjtype, defaclacl::text
            FROM pg_default_acl ORDER BY 1, 2, 3
        """,
        "права столбцов": """
            SELECT c.relname, a.attname, a.attacl::text FROM pg_attribute AS a
            JOIN pg_class AS c ON c.oid = a.attrelid
            WHERE c.relnamespace = 'public'::regnamespace AND NOT a.attisdropped
                AND a.attacl IS NOT NULL ORDER BY 1, 2
        """,
    }
    state = {label: conn.execute(query).fetchall() for label, query in queries.items()}
    for name, kind, *_ in state["таблицы, последовательности, индексы"]:
        if kind == "r":
            statement = sql.SQL("""
                SELECT count(*), md5(string_agg(value, ',' ORDER BY value))
                FROM (SELECT to_jsonb(row)::text AS value FROM public.{} AS row) AS table_rows
            """)
        elif kind == "S":
            statement = sql.SQL("SELECT last_value, is_called FROM public.{}")
        else:
            continue
        state[name] = conn.execute(statement.format(sql.Identifier(name))).fetchall()
    return state


def migrator(contour, *arguments, **changes):
    environment = os.environ | dict(
        DB_USER=f"svc_platform_{contour}_migrator", DB_PASSWORD=os.environ[f"VEQTA_TEST_{contour.upper()}_MIGRATOR"],
        DJANGO_SETTINGS_MODULE="config.migration",
    ) | changes
    return subprocess.run(
        [sys.executable, *arguments], env=environment, capture_output=True, text=True, check=False, timeout=45,
    )


def workwear_migrations(conn):
    return conn.execute("SELECT name FROM public.django_migrations WHERE app = 'workwear' ORDER BY name").fetchall()


def object_ids(conn):
    return conn.execute("""
        SELECT oid FROM pg_class WHERE relnamespace='public'::regnamespace
        UNION ALL SELECT oid FROM pg_proc WHERE pronamespace='public'::regnamespace
        UNION ALL SELECT oid FROM pg_constraint WHERE connamespace='public'::regnamespace
        UNION ALL SELECT oid FROM pg_trigger WHERE tgrelid IN (
            SELECT oid FROM pg_class WHERE relnamespace='public'::regnamespace
        )
        ORDER BY 1
    """).fetchall()


def check_column_drift(owner):
    # Отдельные GRANT имитируют отклонения на ранее применённой схеме.
    owner.execute("""
        GRANT SELECT (id) ON public.django_migrations TO PUBLIC;
        GRANT INSERT (app) ON public.django_migrations TO svc_platform_prod;
        GRANT SELECT (name) ON public.django_migrations TO svc_platform_dev_migrator;
        GRANT SELECT (ctid) ON public.django_migrations TO svc_platform_dev;
        GRANT UPDATE (details) ON public.workwear_workwearevent TO svc_platform_dev, svc_platform_prod;
        GRANT SELECT (ctid) ON public.workwear_workwearevent TO svc_platform_dev_migrator;
        ALTER TABLE public.workwear_workwearevent DISABLE TRIGGER ww_event_no_truncate;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON SEQUENCES TO svc_platform_prod;
    """)
    with psycopg.connect(dbname="postgres", user="postgres", connect_timeout=5, autocommit=True) as administrator:
        administrator.execute("GRANT svc_platform_dev TO svc_platform_prod WITH INHERIT TRUE")
        administrator.execute("ALTER ROLE svc_platform_prod IN DATABASE veqta_prod SET session_replication_role = replica")
        try:
            before = inventory(owner)
            audit = migrator("prod", "-m", "scripts.database_access")
            assert audit.returncode != 0, audit.stdout
            for expected in (
                "права столбца: public.django_migrations.id",
                "права столбца: public.django_migrations.name",
                "права столбца: public.django_migrations.app",
                "права столбца: public.django_migrations.ctid",
                "права столбца: public.workwear_workwearevent.details",
                "права столбца: public.workwear_workwearevent.ctid",
                "права по умолчанию (S)",
                "недопустимое членство: svc_platform_prod → svc_platform_dev",
                "недопустимая настройка session_replication_role",
                "межконтурный доступ: svc_platform_prod → veqta_dev",
                "public.workwear_workwearevent.ww_event_no_truncate",
            ):
                assert expected in audit.stderr, audit.stderr
            assert before == inventory(owner)
        finally:
            administrator.execute("REVOKE svc_platform_dev FROM svc_platform_prod")
            administrator.execute("ALTER ROLE svc_platform_prod IN DATABASE veqta_prod RESET session_replication_role")
    owner.execute("""
        ALTER TABLE public.workwear_workwearevent ENABLE TRIGGER ww_event_no_truncate;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE SELECT ON SEQUENCES FROM svc_platform_prod;
    """)
    print("Проверка только для чтения выявляет изменения ACL столбцов, прав по умолчанию, членства, изоляции и триггеров")


def check_upgrade(contour):
    audit_args = ("-m", "scripts.database_access")
    with connect(contour, migration=True) as owner:
        initial_history = [("0001_initial",)]
        if contour == "dev":
            assert owner.execute("""
                SELECT has_sequence_privilege('svc_platform_dev', 'public.django_migrations_id_seq', 'SELECT'),
                       has_function_privilege('svc_platform_dev', 'public.ww_reject_event_change()', 'EXECUTE')
            """).fetchone() == (True, True)
        else:
            initial_history.append(("0002_database_acl",))
            check_column_drift(owner)
        assert workwear_migrations(owner) == initial_history
        before = inventory(owner)
        identities = object_ids(owner)
        assert before["workwear_request"][0][0] > 0 and before["workwear_workwearevent"][0][0] > 0

        with owner.transaction():
            owner.execute("LOCK TABLE public.django_migrations IN SHARE MODE")
            failed = migrator(contour, "manage.py", "migrate", "--noinput", PGOPTIONS="-c lock_timeout=2000")
            assert failed.returncode != 0 and "lock timeout" in failed.stderr, failed.stderr
            assert workwear_migrations(owner) == initial_history
            assert before == inventory(owner)

        for arguments in (("manage.py", "migrate", "--noinput"), (*audit_args, "--protect-migrations"), audit_args):
            result = migrator(contour, *arguments)
            assert result.returncode == 0, result.stdout + result.stderr
        assert workwear_migrations(owner) == [("0001_initial",), ("0002_database_acl",), ("0003_event_access",)]
        assert object_ids(owner) == identities
        after = inventory(owner)
        changed = {
            "django_migrations", "django_migrations_id_seq", "права столбцов", "права по умолчанию",
            "таблицы, последовательности, индексы", "функции",
        }
        assert all(after[label] == data for label, data in before.items() if label not in changed)
        assert after["права столбцов"] == []

        for arguments in (("manage.py", "migrate", "--noinput"), (*audit_args, "--protect-migrations"), audit_args):
            result = migrator(contour, *arguments)
            assert result.returncode == 0, result.stdout + result.stderr
        assert after == inventory(owner)

    with connect(contour) as runtime:
        assert runtime.execute("SELECT count(*) FROM public.workwear_workwearevent").fetchone() == before["workwear_workwearevent"][0][:1]
        for statement in (
            "SELECT id FROM public.django_migrations WHERE false",
            "SELECT name FROM public.django_migrations WHERE false",
            "SELECT ctid FROM public.django_migrations WHERE false",
            "INSERT INTO public.django_migrations (app) SELECT 'probe' WHERE false",
            "UPDATE public.workwear_workwearevent SET details = '{}' WHERE false",
        ):
            try:
                runtime.execute(statement)
            except psycopg.errors.InsufficientPrivilege:
                continue
            raise AssertionError(f"Прикладной роли разрешена операция: {statement}")
    print(f"{contour.upper()}: обновление с {initial_history[-1][0]}, откат и повторный запуск подтверждены")


def check_recovery(restore_port):
    with connect("prod", migration=True) as original, connect("prod", migration=True, port=restore_port) as restored:
        source_state = inventory(original)
        restored_state = inventory(restored)
        changed = {label for label in source_state.keys() | restored_state.keys()
                   if source_state.get(label) != restored_state.get(label)}
        assert not changed, changed
        assert source_state["workwear_request"][0][0] > 0
        assert source_state["workwear_workwearevent"][0][0] > 0
        assert restored.execute("""
            SELECT count(*) FROM pg_roles WHERE rolname LIKE 'veqta%%'
        """).fetchone() == (0,)
    with connect("prod", port=restore_port) as runtime:
        assert runtime.execute("SELECT count(*) FROM public.workwear_request").fetchone() == source_state["workwear_request"][0][:1]
        try:
            runtime.execute("SELECT id FROM public.django_migrations")
        except psycopg.errors.InsufficientPrivilege:
            pass
        else:
            raise AssertionError("После восстановления доступен журнал миграций")
    print("pg_restore: данные, владельцы, индексы, ограничения, триггеры, ACL и права по умолчанию совпадают")

    smoke = """
from django.contrib.auth import get_user_model
from django.test import Client
from workwear.models import Request, WorkwearEvent

client = Client(HTTP_HOST="localhost", HTTP_X_FORWARDED_PROTO="https")
client.force_login(get_user_model().objects.get(username="coldstart_admin"))
assert client.get("/admin/").status_code == 200
assert client.get("/workwear/").status_code == 200
assert Request.objects.filter(status="closed").exists()
assert WorkwearEvent.objects.exists()
"""
    names = (
        "PATH", "HOME", "LANG", "LD_LIBRARY_PATH", "PYTHONPATH",
        "VEQTA_ENV", "DB_NAME", "DB_HOST", "DB_SSLMODE", "DJANGO_SECRET_KEY",
        "DJANGO_ALLOWED_HOSTS", "DJANGO_DEBUG", "DJANGO_TRUST_PROXY", "DJANGO_SECURE_COOKIES",
        "DJANGO_CSRF_TRUSTED_ORIGINS",
    )
    environment = {name: os.environ[name] for name in names if name in os.environ}
    environment.update(
        DB_PORT=restore_port, DB_USER="svc_platform_prod",
        DB_PASSWORD=os.environ["VEQTA_TEST_RESTORED_RUNTIME"], DJANGO_SETTINGS_MODULE="config.settings",
    )
    subprocess.run(
        [sys.executable, "manage.py", "shell", "-c", smoke], env=environment, check=True, timeout=30,
    )
    print("Восстановленная PROD: Admin, Workwear и история доступны под Runtime")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--upgrade":
        check_upgrade(sys.argv[2])
    elif len(sys.argv) == 2:
        check_recovery(sys.argv[1])
    else:
        check_isolation()
