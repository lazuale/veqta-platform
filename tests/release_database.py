"""Проверки ролей и восстановления в кластерах tests/postgresql_release.sh."""
import os
import subprocess
import sys

import psycopg
from psycopg import sql


def connect(contour, *, migration=False, database_contour=None, port=None):
    kind = "migrator" if migration else "runtime"
    role = f"svc_platform_{contour}" + ("_migrator" if migration else "")
    credential = "RESTORED" if port else contour.upper()
    return psycopg.connect(
        host="127.0.0.1", port=port or os.environ["DB_PORT"], sslmode="disable",
        dbname=f"veqta_{database_contour or contour}", user=role,
        password=os.environ[f"VEQTA_TEST_{credential}_{kind.upper()}"], connect_timeout=5,
        autocommit=True,
    )


def check_isolation():
    for contour, other in (("dev", "prod"), ("prod", "dev")):
        for migration in (False, True):
            try:
                connect(contour, migration=migration, database_contour=other).close()
            except psycopg.OperationalError as error:
                assert "permission denied for database" in str(error), error
            else:
                raise AssertionError(f"Разрешено подключение {contour} к {other}")

        # Пробные объекты получают права штатной следующей миграции.
        with connect(contour, migration=True) as owner, connect(contour) as runtime:
            owner.execute("""
                CREATE TABLE public.veqta_acl_probe (id bigint GENERATED BY DEFAULT AS IDENTITY, n integer);
                CREATE FUNCTION public.veqta_acl_probe() RETURNS integer LANGUAGE sql AS 'SELECT 1'
            """)
            try:
                assert runtime.execute("INSERT INTO public.veqta_acl_probe (n) VALUES (7) RETURNING id").fetchone() == (1,)
                assert runtime.execute("SELECT n FROM public.veqta_acl_probe").fetchone() == (7,)
                assert runtime.execute("UPDATE public.veqta_acl_probe SET n=8").rowcount == 1
                assert runtime.execute("DELETE FROM public.veqta_acl_probe").rowcount == 1
                for statement in (
                    "SELECT last_value FROM public.veqta_acl_probe_id_seq",
                    "SELECT setval('public.veqta_acl_probe_id_seq', 8)",
                    "SELECT public.veqta_acl_probe()",
                ):
                    try:
                        runtime.execute(statement)
                    except psycopg.errors.InsufficientPrivilege:
                        continue
                    raise AssertionError(f"Превышены права по умолчанию: {statement}")
            finally:
                owner.execute("DROP TABLE public.veqta_acl_probe; DROP FUNCTION public.veqta_acl_probe()")
    print("DEV/PROD: изоляция CONNECT обеих ролей и фактические права новых объектов подтверждены")


def inventory(conn):
    queries = {
        "база": """SELECT datdba::regrole::text, datacl::text
                   FROM pg_database WHERE datname=current_database()""",
        "схема": "SELECT nspowner::regrole::text, nspacl::text FROM pg_namespace WHERE nspname='public'",
        "таблицы, последовательности, индексы": """
            SELECT relname, relkind, relowner::regrole::text,
                   CASE WHEN relkind<>'i' THEN ARRAY(
                       SELECT item::text FROM unnest(coalesce(relacl, acldefault(
                           (CASE WHEN relkind='S' THEN 's' ELSE 'r' END)::"char", relowner
                       ))) AS item ORDER BY 1
                   ) END,
                   CASE WHEN relkind='i' THEN pg_get_indexdef(oid) END
            FROM pg_class WHERE relnamespace='public'::regnamespace AND relkind IN ('r','S','i')
            ORDER BY relname
        """,
        "функции": """
            SELECT proname, proowner::regrole::text, proacl::text, pg_get_functiondef(oid)
            FROM pg_proc WHERE pronamespace='public'::regnamespace ORDER BY proname
        """,
        "триггеры": """
            SELECT tgrelid::regclass::text, tgname, tgenabled, pg_get_triggerdef(oid)
            FROM pg_trigger WHERE NOT tgisinternal AND tgrelid IN
                (SELECT oid FROM pg_class WHERE relnamespace='public'::regnamespace)
            ORDER BY 1, 2
        """,
        "ограничения": """
            SELECT conrelid::regclass::text, conname, contype, convalidated, condeferrable, condeferred,
                   -- При восстановлении PG19 может перенести это приведение на элементы массива.
                   replace(pg_get_constraintdef(oid),
                       '(ARRAY[''draft''::character varying, ''closed''::character varying])::text[]',
                       'ARRAY[(''draft''::character varying)::text, (''closed''::character varying)::text]')
            FROM pg_constraint WHERE connamespace='public'::regnamespace ORDER BY 1, 2
        """,
        "права по умолчанию": """
            SELECT defaclrole::regrole::text, defaclnamespace::regnamespace::text,
                   defaclobjtype, defaclacl::text
            FROM pg_default_acl ORDER BY 1, 2, 3
        """,
    }
    state = {label: conn.execute(query).fetchall() for label, query in queries.items()}
    for name, kind, *_ in state["таблицы, последовательности, индексы"]:
        if kind == "r":
            statement = sql.SQL("""
                SELECT count(*), md5(string_agg(value, ',' ORDER BY value))
                FROM (SELECT to_jsonb(row)::text AS value FROM public.{} AS row) AS table_rows
            """)
        elif kind == "S":
            statement = sql.SQL("SELECT last_value, is_called FROM public.{}")
        else:
            continue
        state[name] = conn.execute(statement.format(sql.Identifier(name))).fetchall()
    return state


def migration(*arguments, **changes):
    return subprocess.run(
        [sys.executable, "manage.py", "migrate", *arguments],
        env=os.environ | changes, capture_output=True, text=True, check=False, timeout=30,
    )


def check_recovery(restore_port):
    with connect("prod", migration=True) as original, connect("prod", migration=True, port=restore_port) as restored:
        source_state = inventory(original)
        restored_state = inventory(restored)
        changed = {label for label in source_state.keys() | restored_state.keys()
                   if source_state.get(label) != restored_state.get(label)}
        assert not changed, changed
        assert source_state["workwear_request"][0][0] > 0
        assert source_state["workwear_workwearevent"][0][0] > 0
        assert restored.execute("""
            SELECT count(*) FROM pg_roles WHERE rolname LIKE 'veqta%%'
        """).fetchone() == (0,)
    with connect("prod", port=restore_port) as runtime:
        assert runtime.execute("SELECT count(*) FROM public.workwear_request").fetchone() == source_state["workwear_request"][0][:1]
        try:
            runtime.execute("SELECT id FROM public.django_migrations")
        except psycopg.errors.InsufficientPrivilege:
            pass
        else:
            raise AssertionError("После восстановления доступен журнал миграций")
    print("pg_restore: данные, владельцы, индексы, ограничения, триггеры, ACL и права по умолчанию совпадают")

    target = dict(DB_PORT=restore_port, DJANGO_SETTINGS_MODULE="config.migration")
    result = migration("workwear", "0001", "--noinput", **target)
    assert result.returncode == 0, result.stderr
    recorded = "SELECT count(*) FROM django_migrations WHERE app='workwear' AND name='0002_database_acl'"
    with connect("prod", migration=True, port=restore_port) as owner:
        owner.execute("GRANT SELECT ON django_migrations TO svc_platform_prod")
        owner.execute("GRANT UPDATE ON workwear_workwearevent TO svc_platform_prod")
        assert owner.execute(recorded).fetchone() == (0,)
        with owner.transaction():
            owner.execute("LOCK TABLE django_migrations IN SHARE MODE")
            result = migration("--noinput", PGOPTIONS="-c lock_timeout=2000", **target)
            assert result.returncode != 0 and "lock timeout" in result.stderr, result.stderr
            assert owner.execute(recorded).fetchone() == (0,)
            assert owner.execute("""
                SELECT has_table_privilege('svc_platform_prod', 'django_migrations', 'SELECT'),
                       has_table_privilege('svc_platform_prod', 'workwear_workwearevent', 'UPDATE')
            """).fetchone() == (True, True)

        result = migration("--noinput", **target)
        assert result.returncode == 0, result.stderr
        result = migration("--check", **target)
        assert result.returncode == 0, result.stderr
        assert owner.execute(recorded).fetchone() == (1,)
        after_retry = inventory(owner)
        # Повторная запись миграции получает другой ID и время.
        ignored = {"django_migrations", "django_migrations_id_seq"}
        assert all(after_retry[label] == data for label, data in source_state.items() if label not in ignored)
    print("Обновление с 0001: прерванная миграция откатила ACL, повтор завершился с сохранением данных")


if __name__ == "__main__":
    if len(sys.argv) == 2:
        check_recovery(sys.argv[1])
    else:
        check_isolation()
